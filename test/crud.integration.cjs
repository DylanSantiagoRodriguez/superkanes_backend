// HTTP real, JWT firmado y PostgreSQL aislado. No usa datos de clientes.
const assert = require('node:assert/strict');
const { randomUUID, randomBytes } = require('node:crypto');
const { DataSource } = require('typeorm');
const source = require('../dist/database/migration-data-source').default;
const { resources } = require('../dist/resources/resource-registry');

async function main() {
  const name = `superkanes_test_${randomUUID().replaceAll('-', '')}`;
  let databaseCreated = false, owner, app, jwks;
  const ids = {}, org = randomUUID(), otherOrg = randomUUID(), user = randomUUID();
  let checks = 0;
  try {
    await source.initialize();
    await source.query(`CREATE DATABASE "${name}"`);
    databaseCreated = true;
    owner = new DataSource({ ...source.options, database: name, logging: false });
    await owner.initialize();
    await owner.runMigrations();
    const { SignJWT } = await import('jose');
    const { PasswordService } = require('../dist/auth/password.service');
    const passwordHash = await new PasswordService().hash('Clave sintetica para pruebas 2026!');
    const signingKey = randomBytes(64);
    const issuer = 'local';
    Object.assign(process.env, { NODE_ENV:'test', POSTGRES_DB:name, DB_HOST:'127.0.0.1', AUTH_ISSUER:'integration-api', AUTH_AUDIENCE:'integration', AUTH_JWT_SECRET:signingKey.toString('base64'), SWAGGER_ENABLED:'true' });
    await owner.query("INSERT INTO vet.organizacion(id,nombre) VALUES($1,'Prueba A'),($2,'Prueba B')", [org, otherOrg]);
    await owner.query("INSERT INTO vet.usuario(id,proveedor_identidad,identificador_externo,nombre,email) VALUES($1::uuid,'local',$1::uuid::text,'Operador','root@example.test')", [user]);
    const { NestFactory } = require('@nestjs/core');
    const { AppModule } = require('../dist/app.module');
    const { configureApp } = require('../dist/setup-app');
    app = await NestFactory.create(AppModule, { logger: ['error'] });
    configureApp(app);
    await app.listen(0, '127.0.0.1');
    const base = await app.getUrl();
    const token = async (subject = 'root', aud = 'integration', expiry = '10m') => {
      const userId=subject==='root'?user:subject==='staff'?ids.usuario:randomUUID();
      const sessionId=randomUUID();
      if(subject!=='unknown') {
        await owner.query('INSERT INTO auth.credential(usuario_id,password_hash,platform_admin) VALUES($1,$2,$3) ON CONFLICT DO NOTHING',[userId,passwordHash,subject==='root']);
        await owner.query("INSERT INTO auth.session(id,usuario_id,credential_version,expires_at) VALUES($1,$2,1,now()+interval '1 day')",[sessionId,userId]);
      }
      return new SignJWT({sid:sessionId}).setProtectedHeader({alg:'HS256',typ:'at+jwt'}).setIssuer('integration-api').setAudience(aud).setSubject(userId).setJti(randomUUID()).setIssuedAt().setExpirationTime(expiry).sign(signingKey);
    };
    const adminToken = await token();
    async function request(method, path, body, status = 200, options = {}) {
      const headers = { 'Content-Type': 'application/json', Authorization: `Bearer ${adminToken}`, 'X-Organization-Id': org, ...(method === 'POST' ? { 'Idempotency-Key': randomUUID() } : {}), ...options };
      const response = await fetch(`${base}/api/v1/resources${path}`, { method, headers, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
      const value = response.status === 204 ? null : await response.json();
      assert.equal(response.status, status, `${method} ${path}: ${JSON.stringify(value)}`);
      checks++;
      return value;
    }
    const bodies = {};
    const create = async (name, body, alias = name) => { const result = await request('POST', `/${name}`, body, 201); ids[alias] = result.data.id; bodies[alias] = body; return result.data; };
    const patch = async (name, body, alias = name, status = 200) => {
      const current = await request('GET', `/${name}/${ids[alias]}`);
      return request('PATCH', `/${name}/${ids[alias]}`, body, status, { 'If-Match': `"${current.data.version}"` });
    };
    await request('GET', '/tutor', undefined, 401, { Authorization: '' });
    await request('GET', '/tutor', undefined, 401, { Authorization: `Bearer ${await token('root', 'wrong')}` });
    await request('GET', '/tutor', undefined, 401, { Authorization: `Bearer ${await token('root', 'integration', -60)}` });
    await request('GET', '/tutor', undefined, 401, { Authorization: `Bearer ${await token('unknown')}` });
    const catalog = (await request('GET', '')).resources;
    assert.equal(catalog.length, 47);
    const tutorContract = catalog.find(r => r.name === 'tutor');
    assert.deepEqual(tutorContract.permissions, {create:true,update:true,delete:true});
    assert.equal(tutorContract.fields.find(f => f.name === 'nombres').required, true);
    assert.equal(tutorContract.fields.find(f => f.name === 'id').create, false);
    const petContract = catalog.find(r => r.name === 'mascota');
    assert.deepEqual(petContract.fields.find(f => f.name === 'especie_id').reference, {resource:'especie',field:'id'});
    assert.equal(petContract.fields.find(f => f.name === 'tutor_principal_id').required, true);
    checks++;
    assert.equal(catalog.find(r => r.name === 'mascota_tutor').fields.find(f => f.name === 'mascota_id').update, false);
    assert.deepEqual(catalog.find(r => r.name === 'cita').transitions.completada, []);
    checks += 6;
    const openapi = await (await fetch(base+'/api/docs-json')).json();
    for (const contract of catalog.filter(r => r.create)) {
      const operation = openapi.paths['/api/v1/resources/'+contract.name].post;
      const ref = operation.requestBody.content['application/json'].schema.$ref;
      const schema = openapi.components.schemas[ref.split('/').at(-1)];
      assert.deepEqual(contract.fields.filter(f => f.required && f.create).map(f => f.name).sort(), [...(schema.required ?? [])].sort(), 'Required fields: '+contract.name);
      checks++;
    }
    for (const name of resources.keys()) await request('GET', `/${name}?limit=1`);
    await request('GET', '/missing', undefined, 404);
    const now = new Date().toISOString(), hash = 'a'.repeat(64);
    await create('usuario', { proveedor_identidad: issuer, identificador_externo: 'staff', nombre: 'Staff', email: 'staff@example.test' });
    await owner.query("UPDATE vet.usuario SET identificador_externo=id::text WHERE id=$1",[ids.usuario]);
    bodies.usuario.identificador_externo=ids.usuario;

    await create('organizacion', { nombre: 'Clinica creada por API' });
    await create('sede', { nombre: 'Principal', codigo: '01' });
    await create('membresia', { usuario_id: user }, 'rootMembership');
    await create('membresia', { usuario_id: ids.usuario });
    await create('profesional', { membresia_id: ids.rootMembership, nombre_profesional: 'Veterinario de prueba' });
    await create('rol', { nombre: 'Recepcion' });
    await create('permiso', { codigo: 'custom.read', descripcion: 'Prueba' });
    const [readPermission] = await owner.query("SELECT id FROM vet.permiso WHERE codigo='tutor.read'");
    await create('rol_permiso', { rol_id: ids.rol, permiso_id: readPermission.id });
    await create('asignacion_rol', { membresia_id: ids.membresia, rol_id: ids.rol });
    const staffToken = await token('staff');
    const staffCatalog = (await request('GET', '', undefined, 200, { Authorization: `Bearer ${staffToken}` })).resources;
    assert.deepEqual(staffCatalog.map(r => r.name), ['tutor']);
    assert.deepEqual(staffCatalog[0].permissions, {create:false,update:false,delete:false});
    checks += 2;
    await request('GET', '/tutor', undefined, 200, { Authorization: `Bearer ${staffToken}` });
    await request('GET', '/tutor', undefined, 403, { Authorization: `Bearer ${staffToken}`, 'X-Organization-Id': otherOrg });
    await request('POST', '/tutor', { nombres: 'No', apellidos: 'Permitido' }, 403, { Authorization: `Bearer ${staffToken}` });
    await create('archivo', { proveedor: 'local', contenedor: 'pruebas', ruta_relativa: 'fixtures/evidencia.pdf', nombre_original: 'evidencia.pdf', mime_detectado: 'application/pdf', tamano_bytes: '100', sha256: hash, categoria: 'consentimiento', estado_analisis: 'disponible' });
    await create('tutor', { nombres: 'Ana', apellidos: 'Prueba', email: 'ana@example.test' });
    await create('telefono_tutor', { tutor_id: ids.tutor, numero: '+57000000000' });
    await create('preferencia_comunicacion', { tutor_id: ids.tutor, canal: 'email', finalidad: 'recordatorios', estado: 'aceptada', fuente: 'presencial' });
    await create('especie', { nombre: 'Canino' });
    await create('raza', { especie_id: ids.especie, nombre: 'Mestizo' });
    await create('mascota', { codigo: 'M001', nombre: 'Luna', especie_id: ids.especie, raza_id: ids.raza, tutor_principal_id: ids.tutor });
    await require('./pet-registration.integration.cjs')({request,owner,org,otherOrg,ids,base,adminToken,user});
    const guardians = await request('GET', `/mascota_tutor?filter=${encodeURIComponent(JSON.stringify({ mascota_id: ids.mascota }))}`);
    ids.principal = guardians.data[0].id;
    await patch('mascota_tutor', { autorizado_consentir: true }, 'principal');
    await create('tutor', { nombres: 'Otro', apellidos: 'Tutor' }, 'otherTutor');
    await create('mascota_tutor', { mascota_id: ids.mascota, tutor_id: ids.otherTutor });
    await create('alerta_mascota', { mascota_id: ids.mascota, tipo: 'alergia', descripcion: 'Prueba', severidad: 'moderada' });
    await create('laboratorio', { nombre: 'Laboratorio prueba' });
    await create('medicamento', { nombre_comercial: 'Medicamento prueba', principio_activo: 'Prueba', concentracion: '1 mg', forma_farmaceutica: 'tableta', presentacion: 'caja', laboratorio_id: ids.laboratorio });
    await create('vacuna', { nombre: 'Vacuna prueba', laboratorio_id: ids.laboratorio });
    await create('vacunacion', { mascota_id: ids.mascota, sede_id: ids.sede, vacuna_id: ids.vacuna, aplicada_en: now, peso_kg: '10.000', aplicada_por: ids.profesional, lote: 'L001', descripcion_vacuna_emitida: 'Vacuna prueba' });
    await create('pendiente_vacunal', { mascota_id: ids.mascota, vacunacion_origen_id: ids.vacunacion, vacuna_prevista_id: ids.vacuna, indicacion: 'Refuerzo', fecha_objetivo: '2027-01-01' });
    await create('cita', { mascota_id: ids.mascota, sede_id: ids.sede, tutor_contacto_id: ids.tutor, tipo: 'clinica', inicio: '2027-01-01T10:00:00-05:00', fin: '2027-01-01T11:00:00-05:00', responsable_id: ids.rootMembership });
    await create('recordatorio', { tutor_id: ids.tutor, cita_id: ids.cita, canal: 'email', programado_en: '2026-12-31T10:00:00-05:00', clave_idempotencia: randomUUID() });
    await create('atencion_clinica', { mascota_id: ids.mascota, sede_id: ids.sede, cita_id: ids.cita, fecha_atencion: now, profesional_id: ids.profesional });
    await create('revision_clinica', { atencion_id: ids.atencion_clinica, numero: 1, motivo_consulta: 'Control' });
    const clinicalDocument = {type:'doc',content:[{type:'heading',attrs:{level:2,textAlign:'center'},content:[{type:'text',text:'Historia de Luna'}]},{type:'paragraph',content:[{type:'text',text:'Control clínico. '.repeat(8000),marks:[{type:'bold'}]}]}]};
    const savedDocument = await patch('revision_clinica', {documento:clinicalDocument});
    assert.deepEqual(savedDocument.data.documento, clinicalDocument);
    assert.deepEqual((await request('GET', `/revision_clinica/${ids.revision_clinica}`)).data.documento, clinicalDocument);
    await request('PATCH', `/revision_clinica/${ids.revision_clinica}`, {documento:null}, 412, {'If-Match':'"1"'});
    await patch('revision_clinica', {documento:{type:'doc',content:[{type:'image',attrs:{src:'javascript:alert(1)'}}]}}, 'revision_clinica', 400);
    await request('GET', `/revision_clinica/${ids.revision_clinica}`, undefined, 404, {'X-Organization-Id':otherOrg});
    await require('./clinical-attention.integration.cjs')({request,owner,org,ids,staffToken,now});
    if (process.env.TEST_STORAGE === 'true') await require('./storage.integration.cjs')({base,org,otherOrg,adminToken,staffToken,user,revisionId:ids.revision_clinica,petId:ids.mascota,request,patch});
    await create('tipo_seccion_clinica', { codigo: 'NEURO', nombre: 'Neurologia' });
    await create('plantilla_seccion', { tipo_seccion_id: ids.tipo_seccion_clinica, numero_version: 1, esquema_validacion: { type: 'object', properties: { normal: { type: 'boolean' } }, additionalProperties: false }, publicada_en: now });
    await create('seccion_clinica', { revision_id: ids.revision_clinica, tipo_seccion_id: ids.tipo_seccion_clinica, plantilla_id: ids.plantilla_seccion, datos_estructurados: { normal: true } });
    await create('medicion_clinica', { revision_id: ids.revision_clinica, tipo: 'peso', valor: '10.000', unidad: 'kg', medida_en: now });
    await create('diagnostico', { nombre: 'Control sano' });
    await create('diagnostico_atencion', { revision_id: ids.revision_clinica, diagnostico_id: ids.diagnostico, clasificacion: 'confirmado' });
    await create('prescripcion', { revision_id: ids.revision_clinica, profesional_id: ids.profesional });
    await create('prescripcion_item', { prescripcion_id: ids.prescripcion, medicamento_id: ids.medicamento, descripcion_emitida: 'Prueba', via: 'oral', frecuencia: 'segun indicacion', duracion: 'prueba', instrucciones: 'Datos sinteticos' });
    await create('tipo_servicio', { nombre: 'Bano' });
    await create('servicio_peluqueria', { mascota_id: ids.mascota, sede_id: ids.sede, fecha_servicio: now.slice(0,10), responsable_id: ids.rootMembership, tutor_contacto_id: ids.tutor, telefono_contacto_servicio: '+57000000000' });
    await create('peluqueria_item', { servicio_id: ids.servicio_peluqueria, tipo_servicio_id: ids.tipo_servicio });
    await create('plantilla_consentimiento', { nombre: 'Bano', numero_version: 1, contenido: 'Consentimiento sintetico', publicada_en: now });
    await create('consentimiento', { servicio_id: ids.servicio_peluqueria, plantilla_id: ids.plantilla_consentimiento, documento_archivo_id: ids.archivo, hash_documento: hash });
    await create('firma_consentimiento', { consentimiento_id: ids.consentimiento, tutor_id: ids.tutor, metodo: 'documento_escaneado', evidencia_archivo_id: ids.archivo, hash_documento_aceptado: hash });
    await create('adjunto_clinico', { revision_id: ids.revision_clinica, archivo_id: ids.archivo });
    await create('adjunto_vacunacion', { vacunacion_id: ids.vacunacion, archivo_id: ids.archivo });
    await create('adjunto_peluqueria', { servicio_id: ids.servicio_peluqueria, archivo_id: ids.archivo });
    // GET individual y PATCH de cada tipo creado, incluidas sus restricciones.
    for (const r of resources.values()) {
      if (!r.create) continue;
      const path = `/${r.name}/${ids[r.name]}`;
      const current = await request('GET', path);
      let body = { ...bodies[r.name] }, status = r.update ? 200 : 405;
      if (r.name === 'mascota') delete body.tutor_principal_id;
      if (['archivo', 'plantilla_seccion', 'plantilla_consentimiento', 'vacunacion'].includes(r.name)) status = 409;
      if (r.name === 'recordatorio') body = { estado: 'cancelado' };
      if (r.name === 'consentimiento') body = { estado: 'pendiente' };
      await request('PATCH', path, body, status, { 'If-Match': `"${current.data.version ?? 1}"` });
    }
    // Concurrencia, reintentos y limites del contrato.
    await request('PATCH', `/tutor/${ids.tutor}`, { nombres: 'Ana Maria' }, 428);
    await patch('tutor', { nombres: 'Ana Maria' });
    await request('PATCH', `/tutor/${ids.tutor}`, { nombres: 'Anterior' }, 412, { 'If-Match': '"1"' });
    await request('PATCH', `/tutor/${ids.tutor}`, { nombres: null }, 400, { 'If-Match': '"3"' });
    await request('POST', '/tutor', { nombres: 'Sin apellido' }, 400);
    await request('POST', '/tutor', { nombres: 'Ana', apellidos: 'Prueba', email: 'invalido' }, 400);
    await request('PATCH', `/tutor/${ids.tutor}`, { organizacion_id: otherOrg }, 400, { 'If-Match': '"2"' });
    const retryKey = randomUUID(), retryBody = { nombres: 'Reintento', apellidos: 'Seguro' };
    const retry = await request('POST', '/tutor', retryBody, 201, { 'Idempotency-Key': retryKey });
    assert.equal((await request('POST', '/tutor', retryBody, 201, { 'Idempotency-Key': retryKey })).data.id, retry.data.id);
    await request('POST', '/tutor', { ...retryBody, nombres: 'Distinto' }, 409, { 'Idempotency-Key': retryKey });
    await request('GET', '/tutor?limit=101', undefined, 400);
    await request('GET', `/tutor?filter=${encodeURIComponent('{"nombre;DROP TABLE vet.tutor;--":"x"}')}`, undefined, 400);
    await request('GET', `/tutor/${ids.tutor}`, undefined, 404, { 'X-Organization-Id': otherOrg });
    await request('POST', '/telefono_tutor', { tutor_id: ids.tutor, numero: '123' }, 404, { 'X-Organization-Id': otherOrg });
    await patch('seccion_clinica', { datos_estructurados: { normal: 'invalid' } }, 'seccion_clinica', 400);
    await patch('consentimiento', { estado: 'aceptado' });
    await patch('servicio_peluqueria', { estado: 'recibido', llegada_en: now });
    await patch('servicio_peluqueria', { estado: 'en_servicio', inicio_en: now });
    await patch('revision_clinica', { estado: 'cerrada' });
    await patch('revision_clinica', {documento:null}, 'revision_clinica', 409);
    await patch('seccion_clinica', { hallazgos: 'Cambio tardio' }, 'seccion_clinica', 409);
    await patch('atencion_clinica', { estado: 'cerrada' });
    await patch('vacunacion', { observaciones: 'Cambio tardio' }, 'vacunacion', 409);
    for (const name of ['evento_auditoria', 'evento_salida', 'reporte_emitido']) await request('POST', `/${name}`, {}, 405);
    await request('DELETE', `/vacunacion/${ids.vacunacion}`, undefined, 405, { 'If-Match': '"1"' });
    await request('DELETE', `/telefono_tutor/${ids.telefono_tutor}`, undefined, 204, { 'If-Match': '"2"' });
    await request('GET', `/telefono_tutor/${ids.telefono_tutor}`, undefined, 404);
    await request('DELETE', `/laboratorio/${ids.laboratorio}`, undefined, 204, { 'If-Match': '"2"' });
    assert.equal((await request('GET', `/laboratorio/${ids.laboratorio}`)).data.activo, false);
    const localDate = new Intl.DateTimeFormat('en-CA', { timeZone:'America/Bogota' }).format(new Date());
    const petVersion = (await request('GET', `/mascota/${ids.mascota}`)).data.version;
    await request('PATCH', `/mascota/${ids.mascota}/tutor-principal`, { tutor_id:ids.otherTutor, vigente_desde:localDate }, 200, { 'If-Match': `"${petVersion}"` });
    const principalRows = await owner.query('SELECT tutor_id FROM vet.mascota_tutor WHERE mascota_id=$1 AND es_principal AND vigente_hasta IS NULL',[ids.mascota]);
    assert.deepEqual(principalRows.map(row=>row.tutor_id), [ids.otherTutor]);
    // La misma identidad no puede ampliar sus permisos, y el alcance de sede se hereda.
    await owner.query("INSERT INTO vet.rol_permiso(organizacion_id,rol_id,permiso_id) SELECT $1,$2,id FROM vet.permiso WHERE codigo=ANY($3::text[])", [org, ids.rol, ['rol_permiso.create','revision_clinica.read']]);
    const [writePermission] = await owner.query("SELECT id FROM vet.permiso WHERE codigo='tutor.create'");
    await request('POST', '/rol_permiso', { rol_id: ids.rol, permiso_id: writePermission.id }, 403, { Authorization: `Bearer ${staffToken}` });
    await owner.query('UPDATE vet.asignacion_rol SET sede_id=$1 WHERE id=$2', [ids.sede, ids.asignacion_rol]);
    await request('GET', `/revision_clinica/${ids.revision_clinica}`, undefined, 200, { Authorization: `Bearer ${staffToken}` });
    await request('GET', '/tutor', undefined, 403, { Authorization: `Bearer ${staffToken}` });
    const [secondSite] = await owner.query("INSERT INTO vet.sede(organizacion_id,nombre,codigo) VALUES($1,'Otra sede','02') RETURNING id", [org]);
    await owner.query('UPDATE vet.asignacion_rol SET sede_id=$1 WHERE id=$2', [secondSite.id, ids.asignacion_rol]);
    await request('GET', `/revision_clinica/${ids.revision_clinica}`, undefined, 404, { Authorization: `Bearer ${staffToken}` });
    await owner.query('UPDATE vet.membresia SET activo=false WHERE id=$1', [ids.membresia]);
    await request('GET', '/tutor', undefined, 403, { Authorization: `Bearer ${staffToken}` });
    const docs = await (await fetch(`${base}/api/docs-json`)).json();
    assert.ok(docs.paths['/api/v1/resources/tutor'].post);
    assert.equal(docs.paths['/api/v1/resources/tutor'].post.requestBody.content['application/json'].schema.$ref, '#/components/schemas/CreateTutorDto');
    assert.ok(docs.components.schemas.CreateTutorDto.required.includes('nombres'));
    assert.equal(docs.components.schemas.CreateTutorDto.properties.organizacion_id, undefined);
    assert.equal(docs.paths['/api/v1/resources/{resource}'], undefined);
    assert.equal(docs.paths['/api/v1/resources/vacunacion/{id}'].delete, undefined);
    assert.equal(docs.paths['/api/v1/resources/evento_auditoria'].post, undefined);
    assert.equal([...resources.values()].filter(r => r.create).length, 44);
    console.log(`OK: ${checks} comprobaciones HTTP; 47 recursos consultados y 44 tipos creados; JWT, RBAC, RLS, auditoria, historial, consentimiento, concurrencia e idempotencia. Base temporal eliminada al terminar.`);
  } finally {
    if (app) await app.close();
    if (jwks) await new Promise(resolve => jwks.close(resolve));
    if (owner?.isInitialized) await owner.destroy();
    if (databaseCreated && /^superkanes_test_[a-f0-9]{32}$/.test(name)) await source.query(`DROP DATABASE "${name}" WITH (FORCE)`);
    if (source.isInitialized) await source.destroy();
  }
}
main().catch(error => { console.error(error.message); process.exitCode = 1; });
